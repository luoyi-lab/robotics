# 工程实战中，它们是怎么共存的？
# 不要以为学了 MPC，PID 就淘汰了。在真正的机器人（比如波士顿动力机器狗、大疆无人机）里，它们是打配合的：
# 上层（规划与控制）：用状态空间建模型，用 MPC 算出未来几秒钟机器人每个关节“应该”处于什么姿态、需要多大的前馈力
# 底层（执行与保底）：把 MPC 算出来的目标姿态，发给底层的电机。电机的底层驱动板里，依然跑着简单的 PID 控制器，用来克服摩擦、修正误差