# PID 是“盲人摸象”，状态空间是“看清全貌”，MPC 则是“预知未来”
# PID 控制（W5 学的）：基于“误差”的无模型反馈
# 做法：你闭着眼睛开车（不知道车的重量、不管有没有上坡）。你只靠当前的车速表和车道线，发现偏左了，就往右打方向盘（P项）；发现偏右了，就往左打
# 特点：不需要知道物理模型。我不懂汽车发动机原理，也不懂牛顿定律，我只要根据“当前偏差”去死磕就行
# 缺点：永远慢半拍（滞后）。上坡时，如果动力不够，它必须等到车明显溜坡了（产生巨大误差），才开始拼命踩油门

# 状态空间方程：基于“模型”的上帝视角
# 做法：你打开了汽车的说明书，知道了汽车的重量 m、发动机的马力B、当前的坡度和车速（状态 x）。你列出了一个完美的数学矩阵：
# x˙=Ax+Bu
# 特点：这是现代控制理论的基石。有了这个模型，你不仅能算出当前需要多大推力，还能通过算特征值（比如今天算的）预判这辆车会不会翻车、震动频率是多少
# 关键点：状态空间方程本身不是一种控制方法，它是一种描述物理世界的语言。就好比是数学公式，你得往里面填控制算法（比如 LQR、MPC）
# (注：今天的离散化 ZOH 和欧拉法，只是为了让计算机能算懂这个状态方程，属于纯数学工具)

# MPC 等模型预测控制（以后要学的）：基于模型的“预知未来”
# 做法：你不仅看说明书（有模型），还开着高德地图（预知未来）
# 前方 100 米有个大坑，我提前 3 秒就松油门；前方有个长下坡，我提前 5 秒轻踩刹车。我还要考虑乘客舒不舒服（约束条件：不能急刹车，不能超速）
# 特点：强烈依赖状态空间模型。MPC 必须建立在今天学的 A,B 矩阵上。它在后台每一毫秒都在计算：“如果我接下来 10 秒这样打方向盘，车会怎么走？哪种打法最省油、最安全？”
# 碾压 PID 的地方：PID 只能等遇到坑了再补，MPC 能提前避开坑

#   控制方法	        核心思想	            需要物理模型吗？	   能预测未来吗？	        相当于什么？
#   PID (W5)	   有错就纠，死磕误差	       不需要（无脑调参）	    不能（反应滞后）	    蒙着眼睛开车的莽汉
#   状态空间 (W6)	把系统写成矩阵描述	         这就是模型本身	        能算出固有频率等	    拿到汽车说明书
