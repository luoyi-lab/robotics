# 从今天开始，不再“事后补救”，而是要“提前算好账”。这也就是机器人领域大名鼎鼎的计算力矩法（CTC）的开端
# 第一部分 为什么要学动力学？
# 在 W5 中，PID 逻辑是：看到误差 → 产生力。
# 缺陷：它是被动的。如果目标是一个很重的机械臂，PID 必须等机械臂因为重力往下掉了一点，产生误差了，它才会拼命加大电流去拉。这就叫“事后补救”

# 动力学（前馈）的逻辑是：提前计算 → 产生力。
# 你在出发前，已经知道了这节机械臂有多重、重心在哪。你直接算出：“为了让它停在这个角度，我需要输出 10 牛的力矩”。你直接把 10 牛的力给上去，根本不需要等误差发生

# 真实世界的终极公式：总力矩 = 动力学前馈 (提前算出的重力/惯性补偿) + PID 反馈 (兜底修正误差)

# 第二部分 手推单摆（拉格朗日法）
# 设定：质量 m 的小球，挂在长 l 的无质量杆末端。θ 从【竖直向下】量起
# 推导过程见笔记纸 结果如下：
# ┌────────────────────────────────────┐
# │  τ = m·l²·θ̈  +  m·g·l·sinθ         │
# │      └──┬──┘     └────┬────┘       │
# │       惯性项        重力项          │
# └────────────────────────────────────┘
# 这个公式告诉你，要让这个单摆按照你的意愿运动，你要出的力（力矩 τ）必须刚好满足两个条件：
# 第一项 对抗惯性：m·l²·θ̈ 
# 如果你要它加速转动（比如从静止开始甩动），你需要用力
# 转得越快、加速越猛（θ̈  越大），你需要的力越大
# 如果你让它保持匀速或者静止（θ̈ =0），这一项就是 0

# 第二项 对抗重力：m·g·l·sinθ
# 只要它没在最低点（θ≠0），重力就会试图把它拽下去
# 角度 θ 越大（越接近水平），sinθ 越大，重力带来的阻力力矩越大
# 你要抵消这个重力，必须一直出这个大小的力

# 这就是 W5 纯用 PID 时的盲区！
# 在 W5 中，如果你的目标是把机械臂悬停在某个角度θ=0.5），此时 θ̈ =0，上述公式告诉你，你需要输出 
# τ=mglsin(0.5) 的力。
# 但在 W5 的纯 PID 中，由于没有前馈，一开始 PID 以为是 0，直到机械臂因为重力掉下来了，产生误差了，PID 才开始慢慢累积 I 项
# 这就是为什么 I 项（积分器）总是在默默“攒力”，它其实是在帮你算出这个重力项！ 今天直接通过物理公式，提前把这个力算出来了

