# IK 逆运动学的几何直觉 
# 1.先搞清楚IK是什么
# FK：已知 θ1, θ2  →  求末端 (x, y)  一定有解 并且一定只有一个解
# IK：已知 (x, y)  →  求 θ1, θ2
# IK有两个特殊的麻烦 多解和无解的问题 这也是IK比FK难的多的原因

# 2.工作空间：为什么太近也够不到（这一部分详见机器人学）
# 设末端到原点的距离 r = √(x² + y²)。
# 两连杆 + 末端，其实构成一个三角形，三条边是 L1、L2、r。
# 三角形要成立，必须满足：|L1 - L2|  ≤  r  ≤  L1 + L2
# 想象 L1 = 1、L2 = 0.8。
# 两根连杆折到极限时，小臂整个缩回大臂上，末端停在离原点 1 - 0.8 = 0.2 的地方 —— 再也进不去了。
# 正中间那一小块，是空的。
#        ╭───────────────╮
#      ╭─┘               └─╮
#     │    ╭─────────╮      │      ← 外圈半径 L1+L2
#     │   │           │      │         内圈半径 |L1-L2|
#     │   │   空 洞   │      │
#     │    ╰─────────╯      │
#      ╰─╮               ╭─┘
#        ╰───────────────╯
# 如果 L1 == L2，内圈半径是 0，甜甜圈变成实心圆，原点也够不到（要完全折起来才行，那是一个奇异点）

# 3.余弦定理：把 r 换成 θ2
# 末端位置：
# x = L1·cosθ1 + L2·cos(θ1 + θ2)
# y = L1·sinθ1 + L2·sin(θ1 + θ2)
# 两边平方再相加：
# r² = x² + y² = L1² + L2² + 2·L1·L2·cos(θ2)
# 整理得到
# cos θ2 = (x² + y² - L1² - L2²) / (2·L1·L2)
# 拿两个极端验证一下：
# θ2 = 0（完全伸直）：cos0 = 1 → r² = (L1+L2)²
# θ2 = π（完全折回）：cosπ = -1 → r² = (L1-L2)²

# 4.代码训练：画一张图 跑起来之后屏幕上出现2000个点 
# 绿色的表示“这个位置机械臂够得到”，红色的表示“够不到”。最后你会看到一个绿色的甜甜圈，外面包着一圈红色
import numpy as np
import matplotlib.pyplot as plt

# ——————— 第 1 块：机械臂参数 ———————
L1 = 1.0
L2 = 1.0

# ——————— 第 2 块：核心函数 ———————
def reachable(x, y, L1=1.0, L2=0.5):
    """给一个点 (x, y)，返回 True 表示够得到，False 表示够不到。"""
    r = np.sqrt(x * x + y * y)      # 末端到原点的距离
    # 核心逻辑：必须在最小半径和最大半径之间
    return abs(L1 - L2) <= r <= L1 + L2   # abs是绝对值的意思

# ——————— 第 3 块：撒 2000 个点 ———————
# 在 [-2.5, 2.5] 的范围内随机撒点
xs = np.random.uniform(-2.5, 2.5, 2000)
ys = np.random.uniform(-2.5, 2.5, 2000)

# ——————— 第 4 块：分类 + 画图 ———————
ok_x, ok_y = [], []      # 装“够得到”的点的坐标
no_x, no_y = [], []      # 装“够不到”的点的坐标

for i in range(2000):
    if reachable(xs[i], ys[i]):
        ok_x.append(xs[i])
        ok_y.append(ys[i])
    else:
        no_x.append(xs[i])
        no_y.append(ys[i])

# 画图
plt.scatter(no_x, no_y, s=4, c='red')    # 红色的：够不到 size设为4 
plt.scatter(ok_x, ok_y, s=4, c='green')  # 绿色的：够得到
plt.gca().set_aspect('equal')            # plt.gca()：Get Current Axes，意思是“获取当前的坐标系”。
                                         # .set_aspect('equal')：把 X 轴和 Y 轴的长宽比例锁定为 1:1。
plt.show()

# 5.验证

print(reachable(0.0, 0.5, L1=1, L2=1)) #  True
print(reachable(0.0, 0.5, L1=1.5, L2=0.5)) #  False
print(reachable(2.0, 0.0, L1=1, L2=1)) #  True
print(reachable(2.01, 0.0, L1=1, L2=1)) #  False
print(reachable(0.0, 0.0, L1=1, L2=1)) #  数学上可达 物理上是一个奇点

