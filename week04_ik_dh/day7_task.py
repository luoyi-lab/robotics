# 第4题 标准型 vs 改进型
# (a) 写出两套的公式。
# (b) 根本区别是什么？（不要答「公式顺序不同」，那只是表象）
# (c) 如果把标准型的表直接喂给改进型的公式，会发生什么？程序会报错吗？

# (a) 标准型：动作顺序：绕Z转 → 沿Z平移 → 沿X平移 → 绕X转  Ti = Rz(θ) @ Tz(d) @ Tx(a) @ Rx(α)
#     改进型：动作顺序：绕X转 → 沿X平移 → 绕Z转 → 沿Z平移  Ti = Rx(α) @ Tx(a) @ Rz(θ) @ Tz(d)
# (b) 根本区别在于坐标系附着的参考点不同。
#     标准型：把坐标系建在下一个关节的轴上（连杆末端）。所以n个关节只需要n个矩阵。
#     改进型：把坐标系建在当前关节的轴上（连杆起点）。因此需要额外加一个“末关节到工具端”的变换，n 个关节需要 n+1个矩阵（整列下挪，末尾补一行）
# (c) 不会报错。程序依然能正常跑完并吐出一个结果（矩阵连乘在数学上是合法的）。
#     但是结果是完全错的。算出来的 3D 坐标和姿态将与真实机械臂产生巨大偏差

# 第5题 C++
# (a) 虚表（vtable）是什么？每个对象里存的是什么？
# (b) 为什么基类析构函数必须是 virtual？不写会怎样？程序会崩吗？
# (c) const PController cc(3.0); cc.setKp(5.0); 会怎样？为什么？
# (d) P 控制器的 update(double error)，参数该按值传还是 const double&？为什么？

# (a) 虚表：是编译器为每个包含虚函数的类（在编译期）生成的一张函数指针数组。表里记录了这个类所有虚函数的实际内存地址。
#     对象里存的：每个对象的内存头部都隐藏着一个 vptr（虚表指针）。这个指针指向该对象所属类的虚表。这就是实现多态动态绑定的底层机制。
# (b) 原因：如果用基类指针指向子类对象（Controller* c = new PIDController();）
#     在 delete c; 时，如果析构函数不是虚函数，编译器会根据指针的“静态类型”（基类）去调用析构函数。导致子类的析构函数不执行。
#     后果：子类内部 new 出来的内存（比如 PID 里的数组）永远不会被释放，造成内存泄漏
#     会崩吗：程序通常不会立刻崩溃，但会在未来耗光内存，或者在极少数复杂的继承链中引发未定义行为（导致崩溃）
# (c) 会编译报错（Compile Error）。
#     原因：cc 被声明为 const 常量对象。C++ 的规则极其严格：const 对象只能调用带有 const 修饰的成员函数（如 update() const）。setKp 会修改成员变量，
#     所以不能加 const，从而被编译器直接拦截。这是一种保护机制
# (d) 按值传（double error）。
#     原因：double 是基本数据类型（大小只有 8 个字节）。直接按值传递，CPU 复制这 8 个字节的速度极快。
#     如果用 const double&（引用），底层其实是指针寻址，反而多了一次查地址的开销



 

