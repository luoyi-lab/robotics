# 奇异位形的三层意思
# 第0层（数学表象）：算出了NaN
# 昨天在算 c2 = (x² + y² - L1² - L2²) / (2*L1*L2)
# 因为电脑浮点数精度的问题，算出来的c2可能稍微大于1 比如 1.0000000000000002）
# 这时候去算 sqrt(1 - c2*c2) 根号里面变为负数 结果就是NaN（非数字），程序直接崩溃
# 如何解决：如果算出来 abs(c2) > 1 ，直接用代码强制把它定为 1.0或-1.0

# 第1层 两个解合并 手臂伸直（θ2 = 0）
# θ1=0.3, θ2=0.0
# 目标 = (+1.910673, +0.591040)
# 解 1 = (θ1=+0.3000000000, θ2=+0.0000000000)
# 解 2 = (θ1=+0.3000000000, θ2=-0.0000000000)   ← 同一个姿态
# 类似于你手臂伸直去够一个杯子 手肘朝上和朝下没有区别 是一个姿势

# 第2层 解不唯一 θ2 = π 或 -π  即小臂完全折叠
# 当机械臂完全折叠 末端回到(0, 0)
# 此时大臂 θ1 转多少度都可以 最后的末端永远都在原点 无穷多解
# 电脑会返回给一个毫无意义的随机角度

# 第3层 物理限制 末端真的动不了
# θ2 = 0（完全伸直）时，末端没法沿着手臂方向往前伸了 —— 再伸就断了
# 下面用雅可比把这件事算出来。

# 雅可比矩阵
# 直觉：雅可比矩阵的意思是：我的关节转一丢丢，我的手会在X和Y方向移动多少？ 速度映射 输入的“关节转动速度”，翻译成机器手末端的“空间移动速度”
# 定义：
# 把FK对两个关节角分别求偏导（即对时间t求导 得到速度）：（详细推导见笔记）
# x = L1·cosθ1 + L2·cos(θ1+θ2)
# y = L1·sinθ1 + L2·sin(θ1+θ2)
#      ⎡ ∂x/∂θ1   ∂x/∂θ2 ⎤     ⎡ -L1·s1 - L2·s12    -L2·s12 ⎤
#  J = ⎢                 ⎥  =  ⎢                            ⎥
#      ⎣ ∂y/∂θ1   ∂y/∂θ2 ⎦     ⎣  L1·c1 + L2·c12     L2·c12 ⎦
# 
# 作用如下：
# ⎡vx⎤       ⎡θ̇1⎤
# ⎢  ⎥ = J · ⎢  ⎥        关节速度 → 末端速度
# ⎣vy⎦       ⎣θ̇2⎦

# 关键结论：雅可比矩阵的行列式 det(J) = L1 * L2 * sin(θ2)  可以自己展开手算一遍
# 雅可比矩阵的行列式 det(J) = 0，就是机械臂处于“奇异位形”的数学判定标准（充要条件）
# 注意到 θ1整个消掉了 证明机械臂奇异与否只跟θ2有关 跟手臂转到哪个方向无关

# 奇异意味着什么；
# θ2=1.5708（正常）    rank(J) = 2  满秩2 →  末端能动 2 个方向（平面上任意方向）
# θ2=0.0000（伸直）    rank(J) = 1  秩降为1→  末端只能动 1 个方向（垂直于手臂）

# 在奇异点附近，直接求 J⁻¹ 会炸 所以后面数值IK要用阻尼最小二乘 

# 代码训练
# IK边界 奇异位形
# 核心结论：det(J) = L1·L2·sin(θ2)，θ1 被消掉 → 奇不奇异只看肘部角度
import numpy as np
import matplotlib.pyplot as plt  # 绘图可视化

L1, L2 = 1.0, 1.0

# 先定义FK
def fk_2link(t1, t2, L1=1.0, L2=1.0):
    x = L1 * np.cos(t1) + L2 * np.cos(t1 + t2)
    y = L1 * np.sin(t1) + L2 * np.sin(t1 + t2)
    return x, y

# 定义IK
def ik_2link(x, y, L1=1.0, L2=1.0):
    c2 = (x * x + y * y - L1 * L1 - L2 * L2) / (2 * L1 * L2)
    if c2 > 1.0 + 1e-9 or c2 < -1.0 - 1e-9:
        return []
    c2 = float(np.clip(c2, -1.0, 1.0))  # 强行把 c2 的值限制在 -1.0到1.0之间，越界的部分直接“掐断”  比如：如果原 c2 算出来是 1.0000000002 → 强行砍成 1.0
    s2 = np.sqrt(1.0 - c2 * c2)
    out = []
    for sign in (+1.0, -1.0):
        ss = sign * s2   # 两个θ2互为相反数
        out.append((np.arctan2(y, x) - np.arctan2(L2 * ss, L1 + L2 * c2), np.arctan2(ss, c2)))  # 算出θ1 θ2 ， 塞到out里面  out里面长这样：[(t1_解1, t2_解1), (t1_解2, t2_解2)]
    return out

# 定义雅可比矩阵
def jacobian(t1, t2, L1=1.0, L2=1.0):
    s1, c1 = np.sin(t1), np.cos(t1)
    s12, c12 = np.sin(t1 + t2), np.cos(t1 + t2)
    return np.array([[-L1 * s1 - L2 * s12, -L2 * s12],
                     [ L1 * c1 + L2 * c12,  L2 * c12]])

# 任务A：画出det(J) 找到它什么时候是0
# ===== A：det(J) 随 θ2 的变化 =====
t2s = np.linspace(-np.pi, np.pi, 400)  # 使用 np.linspace 生成横坐标 θ2的数据。从 −π到 π 均匀取 400 个点，用来画出一条平滑的曲线

# TOOD:对每个θ2算det(J) θ1随便 反正会被消掉
detJ = np.array([np.linalg.det(jacobian(0.3, t2))for t2 in t2s])  # 用上面定义的函数算出det

# 理论值 ：L1 * L2 * sin(θ2)
detJ_theory = L1 * L2 * np.sin(t2s)

plt.figure(figsize=(7, 3))  # 新建窗口
plt.plot(t2s, detJ, 'o', ms=3, label='数值 det(J)')  # 画detJ的曲线 上述函数中矩阵算出来的 并添加图例
plt.plot(t2s, detJ_theory, '-', lw=1, label='L1·L2·sin(θ2)')  # 画detJ_theory的曲线 并添加图例
plt.axhline(0, c='k', lw=0.5)  # 画X轴
plt.axvline(0, c='r', lw=0.8, ls='--')
plt.axvline(np.pi, c='r', lw=0.8, ls='--')
plt.axvline(-np.pi, c='r', lw=0.8, ls='--')  # 上述三段分别在X=0、π、-π三个位置画了三条虚线
plt.xlabel('θ2'); plt.ylabel('det(J)'); plt.legend()  # 给X轴Y轴加标签
plt.title('det(J) = L1*L2*sin(theta2)')  # 加标题
plt.show()

# 两个解一合并，det 就该是 0
print('A 验证:')
print('  最大偏差 |数值 - 理论| =', np.max(np.abs(detJ - detJ_theory)))   # abs取绝对值 max取400个点里面最大的那个

# det(J) = 0 的地方就是奇异位形。而且它跟 θ1 无关 —— 你把 θ1 改成任何值，曲线一模一样

# 任务B：两个奇异点 两种完全不同的失稳方式
# ===== B：两个奇异点，两种失稳 =====
print('\nB 验证:')
print('θ1 固定 = 0.3，让 θ2 逼近奇异点，看 IK 返回的 θ1')

print('\n--- B1: θ2 → 0（完全伸直）---')
print(f'{"θ2":>12} {"解1 θ1":>14} {"解2 θ1":>14}  {"解1 θ2":>14} {"解2 θ2":>14}')
for eps in [1e-1, 1e-3, 1e-6, 1e-8]:
    px, py = fk_2link(0.3, eps)  # 先用FK算末端位置
    sols = ik_2link(px, py)   # 再用IK反解
    print(f'{eps:12.0e} {sols[0][0]:14.10f} {sols[1][0]:14.10f}  '  # sols[0][0] 解 1 的 θ₁  sols[0][1]解 1 的 θ2 以此类推
          f'{sols[0][1]:14.3e} {sols[1][1]:14.3e}')

print('\n--- B2: θ2 → π（完全折回）---')
print(f'{"θ2":>16} {"解1 θ1":>14} {"解2 θ1":>14}')
for d in [1e-1, 1e-3, 1e-6, 1e-8]:
    t2 = np.pi - d
    px, py = fk_2link(0.3, t2)
    sols = ik_2link(px, py)
    print(f'{t2:16.12f} {sols[0][0]:14.10f} {sols[1][0]:14.10f}')
# B1：两个解稳步靠拢，最后合并成一个 θ1 始终稳定在 0.3
# B2： θ1 在最后一步突然从 0.3 跳到 1.87，两个解糊成一个乱数 暴力崩塌
# 原理解析 为什么会这样
# 回到公式：
# θ1 = atan2(y, x) - atan2(k2, k1)        k1 = L1 + L2·c2,  k2 = L2·s2

#                             θ2 → 0               θ2 → π
# k1 = L1 + L2 * c2         1 + 1 = 2            1 - 1 = 0
# k2 = L2 * s2                  0                     0
# (x, y)                  离原点很远 正常          (0, 0)
# 结论                   两个atan2都健康          两个都是actan2(0, 0) 无效
# θ2 → π 时 k1、k2、x、y 四个量同时趋近 0，公式彻底退化
# 注意前提：必须 L1 = L2
# 所以要记住：det(J) = 0（几何奇异） θ2 = 0 或 π，跟 L1/L2 无关 。IK 公式 0/0（数值崩） 还要额外满足 L1 = L2

