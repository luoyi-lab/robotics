# 第 1 题 · P / I / D
# (a) P、I、D 各自解决什么问题？一句话一个
# P：根据当前误差提供基本响应，解决“快速靠近目标”的问题
# I：累积历史误差，解决存在恒定扰动时的“稳态误差（差一点点）”问题
# D：根据误差变化率（速度）提供阻尼/刹车，解决“冲过头引起振荡”的问题

# (b) 只有 P 时，在一维质量块（ẍ = u）上会怎样？为什么？
# 现象：系统会围绕目标点做等幅振荡（正弦波），永远停不下来
# 原因：只有 P 相当于一个理想弹簧（无阻尼），系统总能量守恒
# 质量块凭借惯性冲过目标，P 拉回，动能和势能不断转换，但没有任何东西消耗能量

# (c) 为什么「只有 P + I」在这个质量块上会发散？
# 因为该质量块没有物理阻尼（无空气阻力、无摩擦）。
# P 产生振荡，而 I 项会疯狂累积误差并不断向系统注入能量，导致振幅越来越大，直接发散

# 第 2 题 · 积分饱和
# (a) 什么是积分饱和？为什么会发生？
# 定义：执行器（如电机）已到达物理极限（输出饱和），但误差仍存在，导致积分项持续无限累加
# 后果：当系统终于越过目标需要反向减速时，巨大的积分项需要很长时间才能退去，导致极大的超调和长时间恢复

# (b) 举一个具体的数值场景（目标、限幅、增益），说明它为什么会冲过头
# 比如目标从 1 突变到 20，误差 e=19。此时控制器算出的 raw = 190，限幅 u = 10。电机已饱和，但积分器还在按每秒 
# 19×Ki×dt 狂涨。等机械臂终于快到 20 时，积分项已经憋了几百的力，导致它狠狠冲过头，甚至往回倒退

# (c) 三种抗饱和方法（钳位 / 条件积分 / 反计算）各自的原理是什么？
# 钳位（Clamp）：给积分项设一个硬上限（如限制在 ±6），不让它继续变大
# 条件积分（Conditional）：检测到输出饱和（u != raw）时，暂停当拍积分累加
# 反计算（Back-calculation）：把被截断的那部分力差（u - raw）乘以一个系数反馈回积分器，强行把它往回拉

# 第 3 题 · 微分先行
# (a) de/dt 里 e = target - current，目标在 t=5s 从 1 突跳到 20，dt=0.01，Kd=5。算出那一刻 D 项有多大
# 目标突变瞬间，e=20−1=19。上一刻 eprev=0。
# de/dt=(19−0)/0.01=1900D 项 = Kd×de/dt=5×1900=9500

# (b) 微分先行怎么改？
# 不对误差 e 求导，改为对测量值求导：de=−(current−prev_current)/dt

# (c) 为什么位置曲线几乎不变，但仍然必须改？
# 因为实际的物理惯性大，9500的瞬间冲击无法让物理位置在一瞬间发生肉眼可见的位移。
# 但是，如果看控制量 u 的曲线，普通微分会产生巨大的尖峰。在真实硬件中，这会导致电机瞬间过流、烧毁驱动器或打碎齿轮

# 第 4 题 · 关节耦合
# (a) 两关节臂，joint0 靠近基座，joint1 在外侧。哪个方向的影响大？
# 关节1（远端）运动对关节0（近端）的影响大

# (b) 你实验测出的具体数字是多少？
# 锁死 J0，动 J1，J0 误差从 0 涨到 0.00638。
# J0 与 J1 一起动，J1 误差只涨了 5%（从 0.0198 到 0.0208）

# (c) 为什么是单向的？（用物理直觉解释）
# 远端（小臂）高速摆动会产生巨大的离心力和反作用力矩，通过连杆狠狠扯动近端（大臂）
# 反之，近端转动只是给远端提供了一个移动的基座，远端的局部 PID 很容易通过调整自身夹角来补偿

# (d) 这决定了什么时候必须换更高级的控制方法？
# 当机器人高速运动或负载极重时，这种动力学耦合会变成摧毁系统的干扰，
# 必须使用计算力矩法（CTC）或全身控制（WBC）建立完整的动力学模型来显式补偿

# 第 5 题 · C++
# (a) std::atomic<long long> 和裸 long long 在 4 线程各加 200 万次时，结果差多少？给出你实测的数字。
# atomic 精确等于 8,000,000。
# 裸 long long 每次测试都不同，大概在 3,200,000 左右，丢失了 60% 的数据。

# (b) std::lock_guard 是什么机制？什么时候自动解锁？
# 这是 RAII（资源获取即初始化） 机制。它在构造时加锁，在离开作用域（遇到大括号 }）时，会通过析构函数自动解锁。

# (c) 控制器的 integral_、prev_val_ 需要加锁吗？为什么？
# 不需要。
# 因为它们是控制器对象的私有成员变量（局部变量），
# 只有控制线程会访问它，它并不是多个线程共享的数据。加锁只会徒增开销，降低性能