# 自测五道题
# Q1 旋转矩阵
# 写出绕 x 轴转 θ 的 3×3 矩阵  然后不计算，直接说出 Rx(90°) 把 y 轴送到哪、把 z 轴送到哪
import numpy as np
def Rx(theta):
    c, s = np.cos(theta), np.sin(theta)
    return np.array([[1 ,0 ,0 ],
                     [0 ,c ,-s],
                     [0 ,s ,c ]])
# Rx(90°) 把 y 轴送z轴，把 z 轴送到-y轴

